import { readFileSync, writeFileSync } from 'node:fs'
const root = new URL('../', import.meta.url)
const read = name => readFileSync(new URL(name, root), 'utf8')
const source = read('src/plugin.cjs')
const bundle = '// Generated by scripts/build.mjs.\n' + source.replace("require('./toolbar.css')", () => JSON.stringify(read('src/toolbar.css')))
const output = new URL('gui-experimental.cjs', root)
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== bundle) throw Error('Run npm run build to refresh the release entry')
} else {
  writeFileSync(output, bundle)
}
