import { read, controlsSource } from './sources.mjs'
import { readFileSync, writeFileSync } from 'node:fs'
const root = new URL('../', import.meta.url)
const source = read('src/plugin.cjs').replace("const { mountControls } = require('./controls.cjs')",
  () => controlsSource().replace('module.exports = { mountControls }', ''))
const bundle = '// Generated by scripts/build.mjs.\n' + source.replace("require('./toolbar.css')", () => JSON.stringify(read('src/toolbar.css')))
const output = new URL('gui-experimental.cjs', root)
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== bundle) throw Error('Run npm run build to refresh the release entry')
} else {
  writeFileSync(output, bundle)
}
